"""TabPFN as a synthesiser, via tabpfn_extensions' TabPFNUnsupervisedModel.

How it generates (read from tabpfn-extensions 0.6.2): starting from an all-NaN
table, columns are filled one at a time in column order, each record drawn from
TabPFN's predictive distribution for that column given the columns already
generated, with the stored training data as in-context examples. Continuous
columns are sampled from TabPFN's discretised ("bar") predictive distribution
at temperature t; categorical columns from the predicted class probabilities
(the temperature does not apply to them). The predictive distributions are
averaged over `n_permutations` orderings of the conditioning columns.

"Fitting" stores the data as context; no weights change. Two consequences:
  - The only fit-level randomness is TabPFN's own ensemble preprocessing,
    controlled by `random_state`, which we tie to the training seed. A new
    training seed changes the fit only through that, so Step 3 is defined but
    expected to add little between-file scatter.
  - Step 4 (bootstrap) changes the context itself.
Each record integrates over TabPFN's approximation to the posterior predictive,
so its extra uncertainty is expected to show up in the within-file variance
u_bar rather than in the between-file variance b_m.

Column order matters for a sequential synthesiser. We use synthpop's visit
order (x2, x1, y), so y is drawn last given both predictors and the two
sequential generators are comparable.

Seeds: `random_state` of both TabPFN estimators = training seed. Sampling uses
torch's global RNG and the permutations use Python's `random`, so every
generate() call seeds those globally with the generation seed.

Warm-up: the first generation in a PROCESS does one-time initialisation that
draws from torch's global RNG, so without it the first file differs from every
later file with the same seed (measured: max difference 15 on y). The first
fit() in a process therefore generates a throwaway 2-row file; later fits skip
it, since it costs a full context pass (~20 s at 500 context rows on CPU).

Built-model cache: TabPFN refits (and by default rebuilds the network) once per
column per permutation, nine times per file. TABPFN_MODEL_CACHE_SIZE=2 keeps the
built classifier and regressor, which cut the cost per file by about a third.
Rebuilding also draws from torch's RNG, so the cache setting changes which
file a seed produces. The wrapper therefore sets it itself rather than leaving
it to the environment.

Non-finite intermediate values: the sampler can return +-inf (see generate()).
In the last column (y) such a value reaches the output and its row is redrawn.
In an earlier column it becomes an input to the next column's prediction and
TabPFN raises TabPFNValidationError ("Input contains infinity ..."), so no
table comes back at all. That generation call is then repeated with a seed
derived from the call's own seed (spawn key (0, j), disjoint from the row
redraws' (attempt,)), at most MAX_REDRAWS times. A call that never fails takes
exactly the path it took before this redraw existed, so files that never hit
the error are bit-identical. The n rows of a failed call count as rejected rows
in `last_n_rejected` (so a file's n_rejected // n_syn is its number of failed
calls) and `last_n_redrawn_calls` counts the calls; each one is logged.

Categorical columns are exactly `discrete_columns`. TabPFNUnsupervisedModel.fit
runs tabpfn_extensions' infer_categorical_features, which ADDS every column with
at most 40 distinct values and more than 10 rows per value
(utils.MAX_UNIQUE_VALUES_FOR_CATEGORICAL, MIN_SAMPLES_PER_CATEGORY). Such a
column is then generated by the classifier, which returns class INDICES 0..K-1,
not the values: on the ACS extract, age (40 integer values, 25-64) came back as
0-39. fit() therefore resets the list to the declared columns after the library's
inference and logs any column the inference had added. In the simulation the
inference adds nothing (x1 and y are continuous, x2 is declared), so the reset
leaves it unchanged.

Size limits: TabPFN refuses CPU inference on more than 1,000 context rows by
default (too slow); `ignore_pretraining_limits=True` lifts that and the
10,000-row pretraining limit. Use a GPU for n_org in the thousands.
"""
from __future__ import annotations

import logging
import os

import numpy as np
import pandas as pd

from src.seeds import set_global_seeds

from .base import Generator

ORDER = ("x2", "x1", "y")
MODEL_CACHE_SIZE = "2"
_WARMED_UP = False                                # per process, see the docstring
MAX_REDRAWS = 20
DISCRETE = ("x2",)
log = logging.getLogger(__name__)


class TabPFNGenerator(Generator):
    name = "tabpfn"

    def __init__(self, temperature: float = 1.0, n_permutations: int = 3,
                 device: str = "auto", order=ORDER, discrete_columns=DISCRETE,
                 ignore_pretraining_limits: bool = True, params: dict | None = None,
                 warmup: bool = True, dequantize=()):
        self.temperature = float(temperature)
        self.n_permutations = int(n_permutations)
        self.device = device
        self.order = list(order)
        self.dequantize = list(dequantize)       # columns to dequantise (see fit)
        self._bounds: dict = {}
        self.discrete_columns = list(discrete_columns)
        self.ignore_pretraining_limits = ignore_pretraining_limits
        self.params = dict(params or {})          # extra TabPFN estimator kwargs
        self.warmup = warmup
        self._model = None
        self.inferred_categorical: list[str] = []
        self.last_n_rejected = 0
        self.last_n_redrawn_calls = 0

    def fit(self, data: pd.DataFrame, *, train_seed: int):
        global _WARMED_UP
        os.environ["TABPFN_MODEL_CACHE_SIZE"] = MODEL_CACHE_SIZE
        from tabpfn import TabPFNClassifier, TabPFNRegressor
        from tabpfn_extensions.unsupervised import TabPFNUnsupervisedModel
        _silence_progress_bars()

        self._columns = list(data.columns)
        missing = set(self.order) ^ set(self._columns)
        if missing:
            raise ValueError(f"order {self.order} does not match columns {self._columns}")
        for c in self.discrete_columns:
            # Classes are sampled as indices 0..K-1 and used as values directly.
            levels = np.unique(data[c])
            if not np.array_equal(levels, np.arange(len(levels))):
                raise ValueError(f"discrete column {c!r} must be coded 0..K-1, got {levels}")

        kw = dict(random_state=int(train_seed), device=self.device,
                  ignore_pretraining_limits=self.ignore_pretraining_limits, **self.params)
        self._model = TabPFNUnsupervisedModel(tabpfn_clf=TabPFNClassifier(**kw),
                                              tabpfn_reg=TabPFNRegressor(**kw))
        declared = [self.order.index(c) for c in self.discrete_columns]
        self._model.set_categorical_features(declared)
        fit_data = data[self.order].astype(float)
        if self.dequantize:
            # Dequantisation: integer-valued columns get U(-0.5, 0.5) noise so the in-context
            # data are as continuous as the values TabPFN generates; generate() rounds them
            # back after the whole file is drawn. Noise stream derived from the training seed.
            rng = np.random.default_rng(np.random.SeedSequence(entropy=int(train_seed),
                                                               spawn_key=(7,)))
            for c in self.dequantize:
                self._bounds[c] = (float(data[c].min()), float(data[c].max()))
                fit_data[c] = fit_data[c] + rng.uniform(-0.5, 0.5, size=len(fit_data))
        self._model.fit(fit_data.to_numpy(dtype=np.float32))
        # getattr: test doubles of the model (tests/test_tabpfn_wrapper.py) have no list
        inferred = getattr(self._model, "categorical_features", declared)
        added = sorted(set(inferred) - set(declared))
        if added:
            log.info("tabpfn: library inferred %s as categorical; kept continuous",
                     [self.order[i] for i in added])
        self._model.set_categorical_features(declared)      # see the module docstring
        self.inferred_categorical = [self.order[i] for i in added]
        if self.warmup and not _WARMED_UP:
            set_global_seeds(int(train_seed))
            self._model.generate_synthetic_data(
                n_samples=2, t=self.temperature, n_permutations=self.n_permutations)
            _WARMED_UP = True
        return self

    def _draw(self, n: int, seed: int) -> pd.DataFrame:
        set_global_seeds(int(seed))
        out = self._model.generate_synthetic_data(
            n_samples=int(n), t=self.temperature, n_permutations=self.n_permutations)
        arr = out.detach().cpu().numpy() if hasattr(out, "detach") else np.asarray(out)
        return pd.DataFrame(arr, columns=self.order)[self._columns].astype(float)

    def _draw_safe(self, n: int, seed: int) -> pd.DataFrame:
        """_draw, repeated with derived seeds when TabPFN rejects a non-finite
        value generated in an earlier column (see the module docstring). Any
        other exception propagates unchanged."""
        s = int(seed)
        for j in range(1, MAX_REDRAWS + 2):
            try:
                return self._draw(n, s)
            except Exception as e:
                if not _is_nonfinite_input_error(e):
                    raise
                self.last_n_rejected += int(n)
                self.last_n_redrawn_calls += 1
                log.warning("tabpfn: non-finite intermediate value in a %d-row call "
                            "(seed %d, attempt %d); redrawing the call", int(n), s, j)
                if j > MAX_REDRAWS:
                    break
                s = _derived_seed(int(seed), (0, j))
        raise RuntimeError(f"generation call of {int(n)} rows still failing after "
                           f"{MAX_REDRAWS} redraws (seed {int(seed)})")

    def generate(self, n: int, *, gen_seed: int) -> pd.DataFrame:
        """n rows, all finite. TabPFN's sampler inverts the predictive CDF bucket
        by bucket; when a tail bucket's float32 probability is ~0 it can return
        +-inf (about 1 value in 10^5 rows at n_org 5000). Such rows are rejected
        and redrawn with seeds derived from gen_seed, so a file is still
        reproducible from its seed; `last_n_rejected` counts the rejected rows
        and the harness records it. Finite extremes are kept: they are draws
        from TabPFN's predictive distribution, not arithmetic failures.
        Generation calls that fail on a non-finite intermediate value are
        redrawn by _draw_safe and counted in the same total."""
        if self._model is None:
            raise RuntimeError("generate() before fit()")
        self.last_n_rejected = 0
        self.last_n_redrawn_calls = 0
        df = self._draw_safe(n, gen_seed)
        bad = ~np.isfinite(df.to_numpy()).all(axis=1)
        self.last_n_rejected += int(bad.sum())
        attempt = 0
        while bad.any():
            attempt += 1
            if attempt > MAX_REDRAWS:
                raise RuntimeError(f"{int(bad.sum())} rows still non-finite after "
                                   f"{MAX_REDRAWS} redraws")
            k = int(bad.sum())
            seed = np.random.SeedSequence(entropy=int(gen_seed), spawn_key=(attempt,))
            extra = self._draw_safe(max(k, 2), int(seed.generate_state(1, np.uint32)[0])).iloc[:k]
            df.loc[bad, :] = extra.to_numpy()
            new_bad = ~np.isfinite(extra.to_numpy()).all(axis=1)
            self.last_n_rejected += int(new_bad.sum())
            bad = ~np.isfinite(df.to_numpy()).all(axis=1)
        for c in self.dequantize:
            lo, hi = self._bounds[c]
            df[c] = np.clip(np.round(df[c]), lo, hi)
        return df


def _derived_seed(seed: int, key: tuple) -> int:
    ss = np.random.SeedSequence(entropy=int(seed), spawn_key=key)
    return int(ss.generate_state(1, np.uint32)[0])


def _is_nonfinite_input_error(e: BaseException) -> bool:
    """TabPFN's input validation rejecting inf/NaN produced by its own sampler."""
    try:
        from tabpfn.errors import TabPFNValidationError
    except ImportError:                            # older tabpfn: sklearn's ValueError
        TabPFNValidationError = ValueError
    msg = str(e)
    return isinstance(e, TabPFNValidationError) and ("infinity" in msg or "NaN" in msg)


def _silence_progress_bars() -> None:
    """generate_synthetic_data wraps its column loop in tqdm; in a job log that
    is one progress bar per column per file. Replace it with a pass-through."""
    try:
        import tabpfn_extensions.unsupervised.unsupervised as U
        U.tqdm = lambda it, *a, **k: it
    except Exception:
        pass
